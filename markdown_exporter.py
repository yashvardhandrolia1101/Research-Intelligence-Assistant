import json
from typing import Dict, Any

class MarkdownExporter:
    @staticmethod
    def generate_markdown(title: str, sections: Dict[str, Any]) -> str:
        lines = [f"# RIA Research Intelligence Report: {title}", ""]
        for heading, content in sections.items():
            lines.append(f"## {heading}")
            if isinstance(content, (dict, list)):
                lines.append("```json")
                lines.append(json.dumps(content, indent=2))
                lines.append("```")
            else:
                lines.append(str(content))
            lines.append("")
        lines.append("---")
        lines.append("*Generated by RIA — Research Intelligence Assistant. Always verify interpretations against primary literature.*")
        return "\n".join(lines)
