import io
from xml.sax.saxutils import escape
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet

class PDFExporter:
    @staticmethod
    def generate_report_pdf(title: str, sections: dict) -> bytes:
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=50, leftMargin=50, topMargin=50, bottomMargin=50)
        styles = getSampleStyleSheet()
        story = [
            Paragraph(f"<b>RIA — Research Intelligence Report</b>", styles["Normal"]),
            Spacer(1, 6),
            Paragraph(escape(title), styles["Title"]),
            Spacer(1, 14)
        ]
        for heading, body in sections.items():
            story.append(Paragraph(f"<b>{escape(str(heading))}</b>", styles["Heading2"]))
            story.append(Spacer(1, 4))
            safe_body = escape(str(body)).replace("\n", "<br/>")
            story.append(Paragraph(safe_body, styles["Normal"]))
            story.append(Spacer(1, 10))

        story.append(Spacer(1, 16))
        story.append(Paragraph("<i>Generated by RIA — Research Intelligence Assistant. Verify all AI-assisted interpretations against primary source texts.</i>", styles["Italic"]))
        doc.build(story)
        buffer.seek(0)
        return buffer.getvalue()
